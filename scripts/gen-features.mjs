#!/usr/bin/env node
/**
 * Scans feature modules and writes src/shell/generated/features.ts (or --out path)
 * plus a sibling feature-messages.ts (server-only, per-locale dynamic imports).
 * Usage: node scripts/gen-features.mjs [featuresParent] [--out path]
 * Default features dir: src/features under project root.
 * Fixture: node scripts/gen-features.mjs tests/fixtures/gen-features --out /tmp/features.ts
 *   (expects a features/ subdirectory under the given root)
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");

const NL = String.fromCharCode(10);

function parseArgs(argv) {
  let featuresParent = path.join(projectRoot, "src");
  let outFile = path.join(projectRoot, "src/shell/generated/features.ts");

  const rest = [...argv];
  while (rest.length > 0) {
    const arg = rest.shift();
    if (arg === "--out") {
      outFile = path.resolve(rest.shift() ?? "");
      continue;
    }
    if (!arg.startsWith("-")) {
      featuresParent = path.resolve(arg);
      continue;
    }
    throw new Error(`Unknown argument: ${arg}`);
  }

  const featuresDir = path.join(featuresParent, "features");
  return { featuresDir, outFile, featuresParent };
}

function listFeatureDirs(featuresDir) {
  if (!fs.existsSync(featuresDir)) {
    return [];
  }
  return fs
    .readdirSync(featuresDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b));
}

function findContributionsFile(featureDir) {
  for (const name of ["contributions.tsx", "contributions.ts"]) {
    const full = path.join(featureDir, name);
    if (fs.existsSync(full)) {
      return name;
    }
  }
  return null;
}

function hasMessages(featureDir, locale) {
  return fs.existsSync(path.join(featureDir, "messages", `${locale}.json`));
}

function toImportAlias(featuresDir, featureName, file) {
  const relFromSrc = path
    .relative(path.join(projectRoot, "src"), path.join(featuresDir, featureName, file))
    .split(path.sep)
    .join("/");
  return `@/${relFromSrc.replace(/\.tsx?$/, "")}`;
}

function generate(featuresDir, outFile) {
  const features = listFeatureDirs(featuresDir);
  const locales = ["ar", "en", "fr"];

  const header = [
    "/* eslint-disable @typescript-eslint/no-explicit-any */",
    "/** Generated by scripts/gen-features.mjs — do not edit. */",
    "",
  ];

  const contributionImports = [];
  const contributionEntries = [];
  const messageLoaders = { ar: [], en: [], fr: [] };

  for (const feature of features) {
    const featureDir = path.join(featuresDir, feature);
    const contribFile = findContributionsFile(featureDir);
    if (contribFile) {
      const alias = toImportAlias(featuresDir, feature, contribFile);
      const varName = `${feature.replace(/[^a-zA-Z0-9]/g, "_")}_contributions`;
      contributionImports.push(
        `import { contributions as ${varName} } from "${alias}";`,
      );
      contributionEntries.push(
        `  { feature: ${JSON.stringify(feature)}, contributions: ${varName} },`,
      );
    }

    for (const locale of locales) {
      if (hasMessages(featureDir, locale)) {
        const alias = toImportAlias(
          featuresDir,
          feature,
          `messages/${locale}.json`,
        );
        const varName = `${feature.replace(/[^a-zA-Z0-9]/g, "_")}_messages_${locale}`;
        messageLoaders[locale].push({ feature, varName, alias });
      }
    }
  }

  // Client-safe module: contributions only, no message catalogs.
  const lines = [...header, ...contributionImports];
  if (contributionImports.length) lines.push("");
  lines.push("export const featureContributions = [");
  if (contributionEntries.length) {
    lines.push(...contributionEntries);
  }
  lines.push("] as const;");
  lines.push("");

  // Server-only module: one dynamically imported chunk per locale.
  const msgLines = [...header, 'import "server-only";', ""];
  msgLines.push(
    'export type FeatureMessageLocale = "ar" | "en" | "fr";',
    "",
    "export const featureMessageLoaders: Record<",
    "  FeatureMessageLocale,",
    "  () => Promise<Record<string, any>>",
    "> = {",
  );
  for (const locale of locales) {
    msgLines.push(`  ${locale}: async () => {`);
    const entries = messageLoaders[locale];
    if (entries.length) {
      msgLines.push(
        "    const [" + entries.map((e) => e.varName).join(", ") + "] = await Promise.all([",
      );
      for (const e of entries) {
        msgLines.push(`      import("${e.alias}").then((m) => m.default),`);
      }
      msgLines.push("    ]);");
    }
    msgLines.push("    return {");
    for (const e of entries) {
      msgLines.push(`      ${JSON.stringify(e.feature)}: ${e.varName},`);
    }
    msgLines.push("    };");
    msgLines.push("  },");
  }
  msgLines.push("};", "");

  const dir = path.dirname(outFile);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(outFile, lines.join(NL), "utf8");
  fs.writeFileSync(messagesFile(outFile), msgLines.join(NL), "utf8");
}

function messagesFile(outFile) {
  return path.join(path.dirname(outFile), "feature-messages.ts");
}

const { featuresDir, outFile } = parseArgs(process.argv.slice(2));
generate(featuresDir, outFile);
console.log(`Wrote ${outFile} (${listFeatureDirs(featuresDir).length} feature(s))`);
